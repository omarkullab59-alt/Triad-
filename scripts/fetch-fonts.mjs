// Self-host the TRIAD fonts (privacy: no request to Google from visitors' browsers — LG München I, 3 O 17493/20;
// speed: same origin, no extra DNS/TLS). Runs in CI before the build; writes static/assets/fonts/ (gitignored).
// If the download fails the build simply keeps the Google Fonts link.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GOOGLE_CSS = 'https://fonts.googleapis.com/css2?family=Anton&family=Instrument+Serif:ital@0;1&family=Inter+Tight:wght@400;500;600&family=JetBrains+Mono:wght@400;500&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext']);

// Keep only latin/latin-ext @font-face blocks; return [{ css, url }]
export function pickFaces(css) {
  const out = [];
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g;
  let m;
  while ((m = re.exec(css))) {
    if (!KEEP.has(m[1])) continue;
    const url = (m[2].match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    if (url) out.push({ subset: m[1], css: m[2], url });
  }
  return out;
}

async function main() {
  const dir = path.join(ROOT, 'static/assets/fonts');
  const res = await fetch(GOOGLE_CSS, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`css ${res.status}`);
  const faces = pickFaces(await res.text());
  if (!faces.length) throw new Error('no faces');
  fs.mkdirSync(dir, { recursive: true });
  let css = '/* TRIAD fonts — self-hosted, generated by scripts/fetch-fonts.mjs (SIL Open Font License) */\n';
  for (const [i, f] of faces.entries()) {
    const name = `${f.css.match(/font-family:\s*'([^']+)'/)[1].replace(/\W+/g, '-').toLowerCase()}-${i}.woff2`;
    const r = await fetch(f.url);
    if (!r.ok) throw new Error(`font ${r.status}`);
    fs.writeFileSync(path.join(dir, name), Buffer.from(await r.arrayBuffer()));
    css += `/* ${f.subset} */\n${f.css.replace(f.url, `./${name}`)}\n`;
  }
  fs.writeFileSync(path.join(dir, 'fonts.css'), css);
  console.log(`fonts: ${faces.length} faces self-hosted`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.warn(`fonts: kept Google Fonts link (${e.message})`); });
}
